import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const extensionRoot = resolve(scriptDirectory, "..");
const schemaPath = resolve(extensionRoot, "../../docs/protocol/runtime-protocol.schema.json");
const outputPath = resolve(extensionRoot, "src/protocol/generated.ts");
const check = process.argv.includes("--check");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));

function pascalCase(value) {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function literal(value) {
  return typeof value === "string" ? JSON.stringify(value) : String(value);
}

function indent(value, spaces) {
  const prefix = " ".repeat(spaces);
  return value.split("\n").map((line) => prefix + line).join("\n");
}

function tsType(value, depth = 0) {
  if (Array.isArray(value.enum) && value.enum.length > 0) {
    return value.enum.map(literal).join(" | ");
  }
  if (Array.isArray(value.oneOf) && value.oneOf.length > 0) {
    return value.oneOf.map((entry) => tsType(entry, depth)).join(" | ");
  }
  switch (value.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `ReadonlyArray<${tsType(value.items ?? {}, depth)}>`;
    case "object": {
      const properties = value.properties ?? {};
      const names = Object.keys(properties).sort();
      if (names.length === 0) {
        return "Readonly<Record<string, unknown>>";
      }
      const required = new Set(value.required ?? []);
      const lines = names.map((name) => {
        const optional = required.has(name) ? "" : "?";
        return `readonly ${JSON.stringify(name)}${optional}: ${tsType(properties[name], depth + 1)};`;
      });
      return `{\n${indent(lines.join("\n"), (depth + 1) * 2)}\n${" ".repeat(depth * 2)}}`;
    }
    default:
      return "unknown";
  }
}

function typeEntries(values, suffix) {
  return Object.keys(values).sort().map((kind) => ({
    kind,
    name: `${pascalCase(kind)}${suffix}`,
    type: tsType(values[kind]),
  }));
}

function renderTypes(entries) {
  return entries.map((entry) =>
    `export type ${entry.name} = ${entry.type};`
  ).join("\n\n");
}

function renderMap(name, entries) {
  const lines = entries.map((entry) =>
    `readonly ${JSON.stringify(entry.kind)}: ${entry.name};`
  );
  return `export interface ${name} {\n${indent(lines.join("\n"), 2)}\n}`;
}

function renderKinds(name, entries) {
  const values = entries.map((entry) => JSON.stringify(entry.kind)).join(",\n");
  return `export const ${name} = [\n${indent(values, 2)}\n] as const;`;
}

const operations = typeEntries(schema.operations, "Payload");
const events = typeEntries(schema.events, "Data");
const operationEnvelope = tsType(schema.envelope.operation);
const eventEnvelope = tsType(schema.envelope.event);
const problem = tsType(schema.envelope.problem);
const sessionProfileTypes = [
  "session_profile_snapshot",
  "session_profile_patch",
  "session_profile_update",
  "session_tool_catalog",
  "session_list",
  "session_lifecycle_patch",
  "session_lifecycle_update",
  "session_delete",
  "checkpoint_list",
  "checkpoint_restore",
  "checkpoint_fork",
  "session_plan",
].map((name) => ({
  kind: name,
  name: pascalCase(name),
  type: tsType(schema.envelope[name]),
}));

const generated = `// Code generated by scripts/generate-protocol.mjs. DO NOT EDIT.
// Source: docs/protocol/runtime-protocol.schema.json

export const protocolVersion = ${schema.protocol_version} as const;

${renderKinds("operationKinds", operations)}
export type OperationKind = (typeof operationKinds)[number];

${renderKinds("eventKinds", events)}
export type EventKind = (typeof eventKinds)[number];

export type OperationEnvelope = ${operationEnvelope};

export type EventEnvelope = ${eventEnvelope};

export type ProtocolProblem = ${problem};

${renderTypes(sessionProfileTypes)}

${renderTypes(operations)}

${renderMap("OperationPayloadByKind", operations)}

${renderTypes(events)}

${renderMap("EventDataByKind", events)}

export type KnownOperation = {
  readonly [Kind in OperationKind]: Omit<OperationEnvelope, "kind" | "payload"> & {
    readonly kind: Kind;
    readonly payload: OperationPayloadByKind[Kind];
  };
}[OperationKind];

export type KnownEvent = {
  readonly [Kind in EventKind]: Omit<EventEnvelope, "kind" | "data"> & {
    readonly kind: Kind;
    readonly data: EventDataByKind[Kind];
  };
}[EventKind];
`;

if (check) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is a drift failure.
  }
  if (current !== generated) {
    console.error("generated protocol types are stale; run npm run generate:protocol");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
