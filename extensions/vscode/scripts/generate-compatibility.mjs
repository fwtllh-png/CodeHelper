import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const extensionRoot = resolve(scriptDirectory, "..");
const manifestPath = resolve(
  extensionRoot,
  "../../internal/compatibility/compatibility.json",
);
const packagePath = resolve(extensionRoot, "package.json");
const outputPath = resolve(extensionRoot, "src/compatibility/generated.ts");
const packagedManifestPath = resolve(extensionRoot, "compatibility.json");
const check = process.argv.includes("--check");

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const packageJSON = JSON.parse(await readFile(packagePath, "utf8"));
validate(manifest, packageJSON);

const generated = `// Code generated by scripts/generate-compatibility.mjs. DO NOT EDIT.
// Source: internal/compatibility/compatibility.json

export const compatibility = ${JSON.stringify(manifest, null, 2)} as const;
`;
const packagedManifest = `${JSON.stringify(manifest, null, 2)}\n`;

if (check) {
  let current = "";
  let currentManifest = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // Missing generated output is compatibility drift.
  }
  try {
    currentManifest = await readFile(packagedManifestPath, "utf8");
  } catch {
    // Missing packaged manifest is compatibility drift.
  }
  if (current !== generated || currentManifest !== packagedManifest) {
    console.error(
      "generated compatibility data is stale; run npm run generate:compatibility",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
  await writeFile(packagedManifestPath, packagedManifest);
}

function validate(value, extensionPackage) {
  if (!plainObject(value) ||
    value.schema_version !== 1 ||
    typeof value.extension_version !== "string" ||
    value.extension_version !== extensionPackage.version ||
    typeof value.binary_version_range !== "string" ||
    !plainObject(value.acp_protocol) ||
    !positiveInteger(value.acp_protocol.min) ||
    !positiveInteger(value.acp_protocol.max) ||
    value.acp_protocol.min > value.acp_protocol.max ||
    !positiveInteger(value.operation_schema_version)) {
    throw new Error("compatibility manifest version fields are invalid");
  }
  exactKeys(value, [
    "schema_version",
    "extension_version",
    "binary_version_range",
    "acp_protocol",
    "operation_schema_version",
    "required_methods",
    "required_features",
    "targets",
    "channels",
  ], "manifest");
  exactKeys(value.acp_protocol, ["min", "max"], "acp_protocol");
  uniqueStrings(value.required_methods, "required_methods");
  uniqueStrings(value.required_features, "required_features");
  uniqueStrings(value.channels, "channels");
  if (!Array.isArray(value.targets) || value.targets.length === 0) {
    throw new Error("compatibility manifest targets are invalid");
  }
  const targets = new Set();
  for (const target of value.targets) {
    if (!plainObject(target) ||
      typeof target.os !== "string" ||
      typeof target.arch !== "string" ||
      typeof target.vscode_target !== "string") {
      throw new Error("compatibility target is invalid");
    }
    exactKeys(target, ["os", "arch", "vscode_target"], "target");
    const key = `${target.os}/${target.arch}`;
    if (targets.has(key)) {
      throw new Error(`duplicate compatibility target ${key}`);
    }
    targets.add(key);
  }
}

function exactKeys(value, expected, name) {
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  if (actual.length !== wanted.length ||
    actual.some((key, index) => key !== wanted[index])) {
    throw new Error(`compatibility ${name} has unknown or missing fields`);
  }
}

function uniqueStrings(value, name) {
  if (!Array.isArray(value) || value.length === 0 ||
    value.some((entry) => typeof entry !== "string" || entry.length === 0) ||
    new Set(value).size !== value.length) {
    throw new Error(`compatibility ${name} is invalid`);
  }
}

function plainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function positiveInteger(value) {
  return Number.isSafeInteger(value) && value > 0;
}
